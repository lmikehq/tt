  utc_departure: string;
  local_arrival: string;
  utc_arrival: string;
  nightsInDest: null | number;
  quality: number;
  distance: number;
  duration: DurationInfo;
  price: number;
  conversion: ConversionInfo;
  fare: FareInfo;
  price_dropdown: PriceDropdownInfo;
  bags_price: BagsPriceInfo;
